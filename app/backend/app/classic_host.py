"""Classic runtime for the redesigned UI (/v2, /v3) — generated on the fly, read-only.

The new UI embeds the classic app in a transparent layer so every module, popup, chat, AI bot,
check-in gate and tracking hook keeps working. This module serves a *patched copy* of the live
classic files:

    /v2/classic/index.html     ← frontend/index.html  (+ <base href="/">, patched script URL)
    /v2/classic/app.host.jsx   ← frontend/app.jsx      (+ small host-mode hooks)

The classic files on disk are never modified and "/" keeps serving them untouched. Because the copy
is produced from the live source (cached by file mtime), any change to the classic app shows up in
the new UI automatically — nothing to rebuild, nothing left behind.

If a patch no longer matches (the classic code changed shape), the endpoint answers 503 with the
patch name so the new UI shows its modules unavailable instead of running half-wired.
"""
