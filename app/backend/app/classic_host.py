def _read(path: str) -> tuple[float, str]:
    st = os.stat(path)
    with open(path, encoding="utf-8") as f:
        return st.st_mtime, f.read()


def _cached(key: str, path: str, build) -> str:
    mtime = os.stat(path).st_mtime
    with _lock:
        hit = _cache.get(key)
        if hit and hit[0] == mtime:
            return hit[1]
    out = build()
    with _lock:
        _cache[key] = (mtime, out)
    return out


RIQ_REGISTRY = ['UploadModal', 'DprModal', 'UploadsModal', 'CampaignModal', 'ViciPushModal', 'ReassignModal', 'AllocTransferModal', 'JointAllocateModal', 'StaffFormModal', 'LetterModal', 'FlaggedVisitsModal', 'FosVisitReportsModal', 'AttendanceDetail', 'ManageCatalogModal', 'AddProductModal', 'LegalModal', 'TemplateModal', 'TeamLeadOverviewModal', 'AddBranchModal', 'PaymentEditModal', 'LeaveDecisionModal', 'CaseDrawer', 'CycleMIS', 'MyViciAgent', 'EmployeeDocs', 'EIDCard', 'GeocodeButton', 'BackfillAddressButton', 'CorrectColumnsButton', 'RelinkAllocationButton', 'VisitModal', 'StaffModal', 'PerformanceModal', 'EmployeeDashboard', 'RouteHistoryModal', 'LiveRouteModal', 'ReportModal', 'TransferModal', 'MisPivotViewer', 'QR']


def host_js(frontend_dir: str) -> str:
    path = os.path.join(frontend_dir, "app.jsx")

    def build() -> str:
        _, src = _read(path)
        for name in RIQ_REGISTRY:          # every classic component the new UI may open must exist
            if not re.search(r"^function " + name + r"\(", src, re.M):
                raise PatchError(f"classic-host: component '{name}' not found in app.jsx")
        for label, find, repl in _PATCHES:
            src = _patch(src, label, find, repl)
        return src
    return _cached("js", path, build)


def host_html(frontend_dir: str) -> str:
    path = os.path.join(frontend_dir, "index.html")

    def build() -> str:
        _, html = _read(path)
        ver = hashlib.sha1(host_js(frontend_dir).encode()).hexdigest()[:10]
        html, n = re.subn(r'src="app\.jsx\?v=\d+"', f'src="/v2/classic/app.host.jsx?v={ver}"', html)
        if n != 1:
            raise PatchError("classic-host: app.jsx <script> not found in index.html")
        html = re.sub(r"<head>", '<head>\n<base href="/" />', html, count=1, flags=re.I)
        # No loader flash inside the transparent layer.
        html = re.sub(r'<div id="root">[\s\S]*?</div>\s*</div>\s*</div>', '<div id="root"></div>', html, count=1)
        return html
    # Rebuild when either file changes.
    key_path = os.path.join(frontend_dir, "index.html")
    js_m = os.stat(os.path.join(frontend_dir, "app.jsx")).st_mtime
    with _lock:
        hit = _cache.get("html")
        if hit and hit[0] == os.stat(key_path).st_mtime + js_m:
            return hit[1]
    out = build()
    with _lock:
        _cache["html"] = (os.stat(key_path).st_mtime + js_m, out)
    return out
